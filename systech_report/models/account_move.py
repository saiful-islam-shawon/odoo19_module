from odoo import models, fields, api


class AccountMove(models.Model):
    _inherit = 'account.move'

    amount_before_global_discount = fields.Monetary(
        string='Subtotal',
        currency_field='currency_id',
        compute='_compute_amount_before_global_discount',
    )
    previous_due = fields.Monetary(
        string='Previous Due',
        currency_field='currency_id',
        compute='_compute_invoice_due_fields',
        store=False,
    )
    total_due_with_current = fields.Monetary(
        string='Total Due',
        currency_field='currency_id',
        compute='_compute_invoice_due_fields',
        store=False,
    )

    def _get_invoice_report_lines_without_global_discount(self):
        """Return report lines that must appear before the Subtotal row."""
        self.ensure_one()
        return self._get_move_lines_to_report().filtered(
            lambda line: not line._is_global_discount_invoice_line()
        )

    def _get_global_discount_invoice_report_lines(self):
        """Return the global discount lines to print below the Subtotal row."""
        self.ensure_one()
        return self._get_move_lines_to_report().filtered(
            lambda line: line._is_global_discount_invoice_line()
        )

    @api.depends(
        'invoice_line_ids.price_subtotal',
        'invoice_line_ids.sale_line_ids.extra_tax_data',
    )
    def _compute_amount_before_global_discount(self):
        for move in self:
            move.amount_before_global_discount = sum(
                line.price_subtotal
                for line in move.invoice_line_ids
                if line.display_type == 'product'
                and not line._is_global_discount_invoice_line()
            )

    @api.depends('partner_id', 'amount_residual', 'company_id', 'state')
    def _compute_invoice_due_fields(self):
        for move in self:
            if not move.partner_id or move.move_type not in ('out_invoice', 'out_receipt'):
                move.previous_due = 0.0
                move.total_due_with_current = 0.0
                continue

            partner = move.partner_id.commercial_partner_id

  
            lines = self.env['account.move.line'].search([
                ('partner_id', 'child_of', partner.id),
                ('account_id.account_type', '=', 'asset_receivable'),
                ('parent_state', '=', 'posted'),
                ('company_id', '=', move.company_id.id),
            ])
            ledger_balance = sum(lines.mapped('debit')) - sum(lines.mapped('credit'))

  
            current_residual = move.amount_residual if move.state == 'posted' else 0.0
            previous_due = ledger_balance - current_residual

            # Keep the partner ledger balance as-is.  A negative amount is a
            # customer credit/advance and must be shown on both the invoice
            # form and PDF instead of being forced to zero.
            move.previous_due = previous_due

            move.total_due_with_current = move.previous_due + current_residual


class AccountMoveLine(models.Model):
    _inherit = 'account.move.line'

    def _is_global_discount_invoice_line(self):
        """Whether this invoice line was generated by Odoo's global discount."""
        self.ensure_one()
        return any(
            sale_line._is_global_discount()
            for sale_line in self.sale_line_ids
        )
